/**
 * Applies the Material 3 theme.
 *
 * Dark colors come from three sources, in priority order:
 *  1. Dynamic dark scheme derived from the wallpaper (Android 12+).
 *  2. The hand-tuned [DarkScheme] below.
 * The chosen scheme is then nudged so dividers stay visible on OEM builds that
 * ship a very low-contrast outline in their dynamic dark palette.
 */
@Composable
fun CurrencyTheme(
    themeMode: ThemeMode = ThemeMode.System,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val dark = when (themeMode) {
        ThemeMode.System -> isSystemInDarkTheme()
        ThemeMode.Light -> false
        ThemeMode.Dark -> true
    }
    val context = LocalContext.current
    val supportsDynamic = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S

    val scheme = remember(dark, dynamicColor, supportsDynamic, context) {
        val base = when {
            dynamicColor && supportsDynamic && dark -> dynamicDarkColorScheme(context)
            dynamicColor && supportsDynamic -> dynamicLightColorScheme(context)
            dark -> DarkScheme
            else -> LightScheme
        }
        if (dark) base.withReadableOutlines() else base
    }

    MaterialTheme(
        colorScheme = scheme,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}

private fun ColorScheme.withReadableOutlines(): ColorScheme = copy(
    outlineVariant = lerp(outlineVariant, onSurface, 0.08f),
)
