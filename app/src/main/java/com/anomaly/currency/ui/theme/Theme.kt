/** User-selectable appearance. [System] follows the OS-level dark theme. */
enum class ThemeMode {
    System,
    Light,
    Dark,
    ;

    companion object {
        fun fromKey(key: String?): ThemeMode =
            entries.firstOrNull { it.name.equals(key, ignoreCase = true) } ?: System
    }
}

